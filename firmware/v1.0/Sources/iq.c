// ---------------------------
//  Fázis → index (Q15)
//  phase = rad * 32768
// ---------------------------
static inline int phaseToIndex(int32_t phase_q15)
{
    // skála: TABLE_SIZE / (2π)  →  1024 / 6.283185
    // állandó Q15-ben:
    const float scale = (float)TABLE_SIZE / (2.0f * PI);
    int32_t scaled = (int32_t)(phase_q15 / 32768.0f * scale);

    int idx = scaled % TABLE_SIZE;
    if (idx < 0) idx += TABLE_SIZE;
    return idx;
}

// ---------------------------
//       IQ Power Q15
// ---------------------------
int32_t iq_power_q15(int16_t sample, iq_st* st)
{


    int idx = phaseToIndex(st->phase);

    int16_t lo_i = cosTable[idx];
    int16_t lo_q = sinTable[idx];

    // fázis növelés
    st->phase += st->omega;
    static const int32_t FULL_ROT = (int32_t)(2.0f * PI * 32768);
    if (st->phase >= FULL_ROT) st->phase -= FULL_ROT;
    else if (st->phase < 0)   st->phase += FULL_ROT;

    // I/Q keverés: (sample * lo) >> 15
    int32_t i = ( (int32_t)sample * lo_i ) >> 15;
    int32_t q = ( (int32_t)sample * lo_q ) >> 15;

    // LPF: y += α (x − y)
    st->i_filt += ( (int32_t)st->lpfAlpha * (i - st->i_filt) ) >> 15;
    st->q_filt += ( (int32_t)st->lpfAlpha * (q - st->q_filt) ) >> 15;

    // power = I^2 + Q^2   (>>15, hogy normalizált legyen)
    int32_t power =
        ((st->i_filt * st->i_filt) >> 15) +
        ((st->q_filt * st->q_filt) >> 15);

    return power;
}

int16_t scale_to_x15_int(int32_t x, int32_t min, int32_t max, int64_t range ) {
    if (x <= min) return -32768;
    if (x >= max) return 32767;
    int64_t result = (((int64_t)(x - min) << 16) / range) - 32768;

    return (int16_t)result;
}

